      let language = window.MOKDA_I18N.getLanguage();

      function setText(id, value) {
        const element = document.getElementById(id);
        if (element) element.textContent = value;
      }

      function setHTML(id, value) {
        const element = document.getElementById(id);
        if (element) element.innerHTML = value;
      }

      function renderPage() {
        if (document.body.dataset.contentLanguage === language) {
          window.MOKDA_I18N.syncLanguageButtons(language);
          refreshRevealTargets();
          return;
        }
        const copy = pageCopy[language] || pageCopy.ES;
        document.documentElement.lang = window.MOKDA_I18N.getHtmlLang(language);
        document.title = copy.title;
        document.getElementById('meta-description')?.setAttribute('content', copy.metaDescription);
        document.getElementById('og-title')?.setAttribute('content', copy.title);
        document.getElementById('og-description')?.setAttribute('content', copy.metaDescription);
        document.getElementById('twitter-title')?.setAttribute('content', copy.title);
        document.getElementById('twitter-description')?.setAttribute('content', copy.metaDescription);

        setText('mobile-about-link', copy.nav.about);
        setText('mobile-products-link', copy.nav.products);
        setText('mobile-qna-link', copy.nav.qna);
        setText('mobile-contact-link', copy.nav.contact);
        setText('socialTitle', copy.socialTitle);
        document.querySelector('#story img').alt = copy.story.imageAlt;
        document.querySelector('#ingredients img').alt = copy.ingredients.imageAlt;
        document.querySelector('#identity img').alt = {KR:'MOKDA 로고와 한글 먹다',ES:'Logotipo MOKDA y su nombre en coreano',EN:'MOKDA logo and its Korean name'}[language];
        setText('storyKicker', copy.story.kicker);
        setText('storyTitle', copy.story.title);
        setHTML(
          'storyBody',
          copy.story.body.map((paragraph) => `<p>${paragraph}</p>`).join(''),
        );
        setText('ingredientsKicker', copy.ingredients.kicker);
        setText('ingredientsTitle', copy.ingredients.title);
        setHTML('ingredientsBody', copy.ingredients.body.map(paragraph => `<p>${paragraph}</p>`).join(''));
        setText('logoKicker', copy.logo.kicker);
        setText('logoTitle', copy.logo.title);
        setHTML('motiveBody', copy.logo.motiveBody.map((item) => `<p>${item}</p>`).join(''));
        setText('historyKicker', copy.history.kicker);
        setText('historyTitle', copy.history.title);

        setText('productCtaKicker', copy.productCta.kicker);
        setText('productCtaTitle', copy.productCta.title);
        setText('productCtaBody', copy.productCta.body);
        setText('productCtaButton', copy.productCta.button);
        ['historyTitle'].forEach((id) => {
          const heading = document.getElementById(id);
          if (!heading) return;
          const usesKoreanDisplay = /[가-힣]/.test(heading.textContent);
          heading.classList.toggle('display-korean', usesKoreanDisplay);
          heading.classList.toggle('display-latin', !usesKoreanDisplay);
        });
        setHTML('timelineList', copy.history.years.map(group => `<article class="about-history-year" aria-labelledby="history-year-${group.year}"><h3 id="history-year-${group.year}" class="about-year-number">${group.year}</h3><ol>${group.items.map(item => `<li class="about-history-event">${item.month ? `<span class="about-event-month">${item.month}</span>` : ''}<div><p>${item.text}</p>${item.detail ? `<p class="about-event-detail">${item.detail}</p>` : ''}</div></li>`).join('')}</ol></article>`).join(''));
        window.MOKDA_FOOTER.render(language);
        window.MOKDA_I18N.syncLanguageButtons(language);
        refreshRevealTargets();
      }

      const revealObserver =
        'IntersectionObserver' in window
          ? new IntersectionObserver(
              (entries) => {
                entries.forEach((entry) => {
                  if (entry.isIntersecting) {
                    entry.target.classList.add('is-visible');
                    revealObserver.unobserve(entry.target);
                  }
                });
              },
              { threshold: 0.12, rootMargin: '0px 0px -8% 0px' },
            )
          : null;

      function refreshRevealTargets() {
        document.querySelectorAll('[data-reveal]').forEach((element) => {
          element.classList.remove('is-visible');
          if (revealObserver) revealObserver.observe(element);
          else element.classList.add('is-visible');
        });
      }

      window.MOKDA_I18N.bindLanguageButtons((nextLanguage) => {
        language = nextLanguage;
        renderPage();
      });

      renderPage();
